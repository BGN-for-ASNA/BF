def _check_intervals_vs_ref(fig, ref_key):
    # ppc_intervals sorts rows by x; the reference is in observation order
    # (obs_index 1..30), so align the reference with argsort(x).
    xo = np.argsort(X)
    assert np.asarray(fig.data[2].x, dtype=float) == pytest.approx(X[xo])
    ll, l, m, h, hh, obs = _interval_bounds(fig)
    ref = RC[ref_key]
    np.testing.assert_allclose(ll, np.array(ref["ll"])[xo], rtol=RTOL, atol=ATOL)
    np.testing.assert_allclose(l, np.array(ref["l"])[xo], rtol=RTOL, atol=ATOL)
    np.testing.assert_allclose(m, np.array(ref["m"])[xo], rtol=RTOL, atol=ATOL)
    np.testing.assert_allclose(h, np.array(ref["h"])[xo], rtol=RTOL, atol=ATOL)
    np.testing.assert_allclose(hh, np.array(ref["hh"])[xo], rtol=RTOL, atol=ATOL)
    np.testing.assert_allclose(obs, Y[xo], rtol=RTOL, atol=ATOL)


def test_ppc_intervals_matches_bayesplot_intervals_data():
    fig = ppc.ppc_intervals(Y, YREP, x=X, prob=0.5, prob_outer=0.9)
    _check_intervals_vs_ref(fig, "intervals")


def test_ppc_ribbon_matches_bayesplot_ribbon_data():
    # ppc_ribbon_data uses the same .ppd_intervals_data bounds as intervals.
    fig = ppc.ppc_ribbon(Y, YREP, x=X, prob=0.5, prob_outer=0.9)
    _check_intervals_vs_ref(fig, "ribbon")


