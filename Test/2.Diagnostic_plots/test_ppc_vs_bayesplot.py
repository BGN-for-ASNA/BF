def _interval_bounds(fig):
    """Extract (ll, l, m, h, hh, observed) per observation from a
    ppc_intervals / ppc_ribbon figure.

    Trace order (ppc.py): 0 = outer interval, 1 = inner interval, 2 = median,
    3 = observed.  ppc_ribbon draws the intervals as polygons
    y = [hi, lo[::-1]]; ppc_intervals as vertical segments
    y = [lo_0, hi_0, None, lo_1, hi_1, None, ...].  Rows are sorted by x.
    """
    n = len(Y)

    def lo_hi(trace):
        v = np.asarray([np.nan if t is None else t for t in trace.y], dtype=float)
        if trace.fill == "toself":
            return v[n:][::-1], v[:n]
        return v[0::3], v[1::3]

    ll, hh = lo_hi(fig.data[0])
    l, h = lo_hi(fig.data[1])
    med = np.asarray(fig.data[2].y, dtype=float)
    obs = np.asarray(fig.data[3].y, dtype=float)
    return ll, l, med, h, hh, obs


def _reflected_kde_1d(data, xs):
    """Scott-bandwidth Gaussian KDE (s = std(ddof=1) * n**(-1/5)) of values in
    [0, 1], reflected at 0 and 1 (bayesplot's boundary correction): the
    sample is augmented with -x and 2-x and normalised by the original n.
    Used to tie the PIT values recomputed here to the curve the figure
    actually plots."""
    data = np.asarray(data, dtype=float)
    n = len(data)
    s = np.std(data, ddof=1) * n ** (-0.2)
    pts = np.concatenate([data, -data, 2.0 - data])
    z = (np.asarray(xs, dtype=float)[:, None] - pts[None, :]) / s
    return np.exp(-0.5 * z * z).sum(axis=1) / (n * s * np.sqrt(2.0 * np.pi))


def _bf_loo_pit(reff=None):
    """Recompute the PIT vector exactly as ppc_loo_pit does when
    log_likelihood is given (same _psis_weights code path, reff default 1.0,
    per-observation weight normalization, `<=` indicator)."""
    pit = np.empty(len(Y), dtype=np.float64)
    for i in range(len(Y)):
        log_w, _ = _psis_weights(LL[:, i], reff=1.0 if reff is None else reff)
        w = np.exp(np.asarray(log_w, dtype=np.float64))
        w /= w.sum()
        pit[i] = float(np.sum(w * (YREP[:, i] <= Y[i])))
    return pit


