# ---------------------------------------------------------------------------
# 9. ppc_boxplot (ggplot2 stat_boxplot quantile.type=7: Q1/median/Q3)
#
# BF samples 20 of the 200 draws with np.random.default_rng(0) (the seed-0
# sample includes draws 3 and 7, 0-based), so the reference yrep_1..yrep_10
# rows do NOT line up with the figure series in general.  Each go.Box trace
# exposes its raw series as y, so: check every series' type-7 quartiles
# against np.percentile of that series' raw values AND against the raw yrep
# row, and check the sampled draws that ARE in the reference (yrep_4,
# yrep_8) plus the observed series against the reference quartiles.
# ---------------------------------------------------------------------------

def test_ppc_boxplot_quartiles():
    fig = ppc.ppc_boxplot(Y, YREP)            # n=20 default
    assert len(fig.data) == 21
    assert fig.data[0].name == "observed"     # observed box first, then predictions
    qy = np.percentile(np.asarray(fig.data[0].y, dtype=float), [25, 50, 75])
    np.testing.assert_allclose(qy, np.array(RC["boxplot"]["y"]), rtol=RTOL, atol=ATOL)

    # ppc_boxplot samples its 20 draws with default_rng(0), in this order
    idx = np.random.default_rng(0).choice(len(YREP), size=20, replace=False)
    n_ref_checked = 0
    for s, t in zip(idx, fig.data[1:]):
        vals = np.asarray(t.y, dtype=float)
        np.testing.assert_allclose(vals, YREP[s], rtol=RTOL, atol=ATOL)
        q = np.percentile(vals, [25, 50, 75])
        np.testing.assert_allclose(q, np.percentile(YREP[s], [25, 50, 75]),
                                   rtol=RTOL, atol=ATOL)
        key = f"yrep_{s + 1}"                 # reference covers draws 1..10 (1-based)
        if key in RC["boxplot"]:
            np.testing.assert_allclose(q, np.array(RC["boxplot"][key]),
                                       rtol=RTOL, atol=ATOL)
            n_ref_checked += 1
    assert n_ref_checked == 2                 # draws 3 and 7 (0-based) sampled


