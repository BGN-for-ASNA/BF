"""Grouped PPC plots (``group=``) in BayesForge/Diagnostic/ppc.py, cross-checked
against the R bayesplot 1.16.0 reference numbers in fixtures/reference.json
(generated by make_reference.R from the same fixtures/input.json arrays; R is
NOT called at test time).

The grouping vector is ``np.arange(30) % 3 + 1``, identical to R's
``rep(1:3, length.out = 30)`` used by make_reference.R, so panel i (levels in
sorted order) corresponds to reference group g = i + 1.

Tolerances: rtol=1e-7, atol=1e-9, as in test_ppc_vs_bayesplot.py: both sides
read the same JSON fixture arrays and the statistics are exact arithmetic
(np.mean vs rowMeans, np.percentile type 7 vs stats::quantile(type = 7)), so
only floating-point summation-order noise (~1e-15) can differ.
"""
import json
import os

import numpy as np
import pytest

from BayesForge.Diagnostic import ppc

RTOL = 1e-7
ATOL = 1e-9

_HERE = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(_HERE, "fixtures", "input.json")) as _f:
    INP = json.load(_f)
with open(os.path.join(_HERE, "fixtures", "reference.json")) as _f:
    REF = json.load(_f)

Y = np.array(INP["continuous"]["y"], dtype=float)          # (30,)
YREP = np.array(INP["continuous"]["yrep"], dtype=float)    # (200, 30)
GROUP = np.arange(30) % 3 + 1                              # == rep(1:3, length.out = 30)
LEVELS = [1, 2, 3]
GREF = REF["continuous"]["grouped"]


def _panel_traces(fig, panel):
    """Traces drawn in subplot ``panel`` (1-based): plotly numbers the axes in
    layout order; the trace attribute is "x" for panel 1, "x2", "x3", ..."""
    want = "x" if panel == 1 else f"x{panel}"
    return [t for t in fig.data if t.xaxis == want]


# ---------------------------------------------------------------------------
# 1. ppc_stat grouped (bayesplot ppc_stat_data(group = group, stat = "mean"))
# ---------------------------------------------------------------------------

def test_ppc_stat_grouped_panels():
    fig = ppc.ppc_stat(Y, YREP, stat="mean", group=GROUP)
    # one KDE trace + one observed-value hover marker per panel
    assert len(fig.data) == 6
    assert fig.layout.height == 380                 # max(360, 260*1 + 120)
    assert fig.layout.title.text == "PPC: mean of y by group"

    vlines = [s for s in fig.layout.shapes if s.type == "line"]
    assert len(vlines) == 3                         # observed line per panel
    kde = [t for t in fig.data if t.name == "mean of each prediction of y"]
    assert len(kde) == 3
    for i, g in enumerate(LEVELS):
        ref = GREF["stat_grouped"][f"g{g}"]
        xs = np.asarray(kde[i].x, dtype=float)
        t_rep = np.array(ref["yrep"], dtype=float)
        # KDE grid spans T(yrep[:, g])
        np.testing.assert_allclose(xs[0], t_rep.min(), rtol=RTOL, atol=ATOL)
        np.testing.assert_allclose(xs[-1], t_rep.max(), rtol=RTOL, atol=ATOL)
        # vline at mean(y[g])
        np.testing.assert_allclose(vlines[i].x0, float(ref["y_obs"]),
                                   rtol=RTOL, atol=ATOL)
        # panel title: level + two-sided p-value
        text = fig.layout.annotations[i].text
        assert text.startswith(f"group = {g} (p = ") and text.endswith(")")
    # legend entries only from the first panel: its KDE trace (showlegend unset)
    # plus its observed-value marker (showlegend True)
    assert sum(t.showlegend is not False for t in fig.data) == 2


# ---------------------------------------------------------------------------
# 2. ppc_intervals grouped (bayesplot ppc_intervals_data(group = group))
# ---------------------------------------------------------------------------

def test_ppc_intervals_grouped_panels():
    fig = ppc.ppc_intervals(Y, YREP, group=GROUP)
    assert len(fig.data) == 4 * len(LEVELS)         # outer/inner/median/observed
    assert fig.layout.title.text == "PPC: Predictive intervals of y by group"
    assert fig.layout.yaxis2.matches == "y"         # shared y axis

    ref = GREF["intervals_grouped"]
    gcol = np.array(ref["group"], dtype=int)
    for i, g in enumerate(LEVELS):
        sel = gcol == g
        outer = np.asarray(fig.data[4 * i].y, dtype=float)      # ll/hh segments
        inner = np.asarray(fig.data[4 * i + 1].y, dtype=float)  # l/h segments
        med = np.asarray(fig.data[4 * i + 2].y, dtype=float)
        obs = np.asarray(fig.data[4 * i + 3].y, dtype=float)
        for got, key in ((outer[0::3], "ll"), (outer[1::3], "hh"),
                         (inner[0::3], "l"), (inner[1::3], "h"),
                         (med, "m"), (obs, "y_obs")):
            np.testing.assert_allclose(got, np.array(ref[key], dtype=float)[sel],
                                       rtol=RTOL, atol=ATOL)
        # x within the panel = 0..n_g-1 (no x given)
        np.testing.assert_allclose(np.asarray(fig.data[4 * i + 2].x, dtype=float),
                                   np.arange(int(sel.sum())))
        assert fig.layout.annotations[i].text == f"group = {g}"


# ---------------------------------------------------------------------------
# 3. ppc_density grouped
# ---------------------------------------------------------------------------

def test_ppc_density_grouped_panels():
    n = 50  # default; yrep has 200 rows, so 50 predicted lines per panel
    fig = ppc.ppc_density(Y, YREP, n=n, group=GROUP)
    assert fig.layout.title.text == "PPC: Density overlay of y by group"
    for i, g in enumerate(LEVELS):
        traces = _panel_traces(fig, i + 1)
        names = [t.name for t in traces]
        assert names.count("Predictions of y") == n
        assert names.count("y (observed)") == 1
        obs = traces[names.index("y (observed)")]
        xs = np.asarray(obs.x, dtype=float)
        # the observed curve's x range lies inside that group's data range
        lo = min(Y[GROUP == g].min(), YREP[:, GROUP == g].min())
        hi = max(Y[GROUP == g].max(), YREP[:, GROUP == g].max())
        assert xs.min() >= lo and xs.max() <= hi
        # observed and predicted curves of the panel share the x grid
        for t in traces:
            np.testing.assert_array_equal(np.asarray(t.x, dtype=float), xs)
        assert fig.layout.annotations[i].text == f"group = {g}"


# ---------------------------------------------------------------------------
# 4. group=None leaves the figures exactly as before
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("fn", ["ppc_stat", "ppc_intervals", "ppc_density"])
def test_group_none_identical(fn):
    call = getattr(ppc, fn)
    fig_plain = call(Y, YREP)
    fig_none = call(Y, YREP, group=None)
    assert fig_plain.to_dict()["data"] == fig_none.to_dict()["data"]
    assert fig_plain.to_dict()["layout"] == fig_none.to_dict()["layout"]


# ---------------------------------------------------------------------------
# 5. mismatched group length raises ValueError
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("fn", ["ppc_stat", "ppc_intervals", "ppc_density"])
def test_group_length_mismatch(fn):
    call = getattr(ppc, fn)
    with pytest.raises(ValueError, match="length"):
        call(Y, YREP, group=np.arange(len(Y) - 1) % 3 + 1)
    with pytest.raises(ValueError, match="length"):
        call(Y, YREP, group=np.ones(len(Y) + 1))


# ---------------------------------------------------------------------------
# 6. grouped layout fixes: shared x (density), legend below, taller panels,
#    axis titles only once, observed value via hover instead of annotation
# ---------------------------------------------------------------------------

def test_ppc_density_grouped_layout():
    fig = ppc.ppc_density(Y, YREP, group=GROUP)
    # x axes shared across all panels
    for ax in ("xaxis2", "xaxis3"):
        assert fig.layout[ax].matches == "x"
    # horizontal legend below the panels, clear of the first row's titles
    assert fig.layout.legend.y < 0
    assert fig.layout.height >= 360
    # "Density" y title only on the first column
    assert fig.layout.yaxis.title.text == "Density"
    assert fig.layout.yaxis2.title.text in (None, "")


def test_ppc_stat_grouped_layout():
    fig = ppc.ppc_stat(Y, YREP, stat="mean", group=GROUP)
    # no "observed ..." annotations overflowing into neighbouring panels
    assert not any(str(a.text).startswith("observed")
                   for a in fig.layout.annotations)
    # one observed-value hover trace per panel, sitting on that panel's vline
    vlines = [s for s in fig.layout.shapes if s.type == "line"]
    assert len(vlines) == len(LEVELS)
    for i, g in enumerate(LEVELS):
        obs = [t for t in _panel_traces(fig, i + 1) if t.name == "observed mean"]
        assert len(obs) == 1
        np.testing.assert_allclose(float(np.asarray(obs[0].x, dtype=float)[0]),
                                   float(vlines[i].x0), rtol=RTOL, atol=ATOL)
    assert fig.layout.legend.y < 0
    assert fig.layout.height >= 360
    # "Density" y title only on the first column
    assert fig.layout.yaxis.title.text == "Density"
    assert fig.layout.yaxis2.title.text in (None, "")


def test_ppc_stat_ungrouped_keeps_observed_annotation():
    fig = ppc.ppc_stat(Y, YREP, stat="mean")
    assert any(str(a.text).startswith("observed mean")
               for a in fig.layout.annotations)
