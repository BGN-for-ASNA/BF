    @staticmethod
    def multivariate_normal(loc=0.0, covariance_matrix=None, precision_matrix=None, scale_tril=None, scale_diag=None, scale_identity_multiplier=None, validate_args=False, allow_nan_stats=True, name='MultivariateNormal', mask=None, shape=(), sample=False, seed=None, obs=None, wrap=True, create_obj=False):
        """
        Generic wrapper for Multivariate Normal.
        Positional order matches the numpyro facade (loc, covariance_matrix, precision_matrix, scale_tril).
        """
        if scale_tril is not None:
            dist = tfd.MultivariateNormalTriL(loc=loc, scale_tril=scale_tril, validate_args=validate_args, allow_nan_stats=allow_nan_stats, name=name)
        elif covariance_matrix is not None:
            dist = tfd.MultivariateNormalTriL(loc=loc, scale_tril=jnp.linalg.cholesky(covariance_matrix), validate_args=validate_args, allow_nan_stats=allow_nan_stats, name=name)
        elif precision_matrix is not None:
            dist = tfd.MultivariateNormalTriL(loc=loc, scale_tril=jnp.linalg.cholesky(jnp.linalg.inv(precision_matrix)), validate_args=validate_args, allow_nan_stats=allow_nan_stats, name=name)
        elif scale_diag is not None or scale_identity_multiplier is not None:
            if scale_diag is None:
                scale_diag = jnp.full(jnp.shape(loc)[-1:], scale_identity_multiplier,
                                      dtype=jnp.result_type(jnp.asarray(loc), float))
            dist = tfd.MultivariateNormalDiag(loc=loc, scale_diag=scale_diag, validate_args=validate_args, allow_nan_stats=allow_nan_stats, name=name)
        else:
            raise ValueError("multivariate_normal needs one of covariance_matrix, precision_matrix, scale_tril, scale_diag or scale_identity_multiplier.")
        return UnifiedDist._finish(dist, shape=shape, sample=sample, seed=seed, obs=obs, wrap=wrap, mask=mask, create_obj=create_obj, name=name)

