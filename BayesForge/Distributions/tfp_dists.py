    def unit(log_factor=0.0, validate_args=False, allow_nan_stats=True, name='Unit', mask=None, shape=(), sample=False, seed=None, obs=None, wrap=True, create_obj=False):
        """
        numpyro ``Unit(log_factor)``: empty-valued factor, log_prob = log_factor.
        """
        dist = _UnitDist(log_factor, validate_args=validate_args, allow_nan_stats=allow_nan_stats, name=name)
        # _UnitDist has event_shape (0,), so _finish's obs branch reinterprets
        # obs.shape[:-1] (its n_event=1), exactly the old len(obs.shape)-1.
        return UnifiedDist._finish(dist, shape=shape, sample=sample, seed=seed, obs=obs, wrap=wrap, mask=mask, create_obj=create_obj, name=name)

    @staticmethod
    def beta_proportion(mean, concentration, validate_args=False, allow_nan_stats=True, name='BetaProportion', shape=(), sample=False, seed=None, obs=None, wrap=True):
        """
        Beta distribution parameterized by mean and concentration.

        mean must lie in the open interval (0, 1): concrete inputs outside it
        raise ValueError (traced inputs are not checked).
        """
        try:
            mean_arr = np.asarray(mean, dtype=float)
        except Exception:
            mean_arr = None  # traced (abstract) input: skip concrete validation
        if mean_arr is not None and bool(np.any((mean_arr <= 0.0) | (mean_arr >= 1.0))):
            raise ValueError(
                "beta_proportion: mean must lie in the open interval (0, 1);"
                " values outside give negative Beta concentrations.")
        concentration1 = mean * concentration
        concentration0 = (1.0 - mean) * concentration
        return UnifiedDist.beta(concentration1=concentration1, concentration0=concentration0, validate_args=validate_args, allow_nan_stats=allow_nan_stats, name=name, shape=shape, sample=sample, seed=seed, obs=obs, wrap=wrap)

    @staticmethod
    def asymmetric_laplace_quantile(loc, scale, quantile, validate_args=False, allow_nan_stats=True, name='AsymmetricLaplaceQuantile', shape=(), sample=False, seed=None, obs=None, wrap=True):
        """
        Asymmetric Laplace distribution parameterized by quantile.
        """
        if not isinstance(quantile, jax.core.Tracer):
            q = np.asarray(quantile)  # numpy: jnp ops are traced inside a model trace
            if bool(np.any((q <= 0) | (q >= 1))):
                raise ValueError(f"quantile must be in the open interval (0, 1), got {quantile}")
        # As numpyro AsymmetricLaplaceQuantile: the classic scale is
        # scale * asymmetry / quantile (q = 0.5, scale 1 -> Laplace(0, 2)).
        asymmetry = jnp.sqrt(quantile / (1.0 - quantile))
        scale = scale * asymmetry / quantile
        return UnifiedDist.asymmetric_laplace(loc=loc, scale=scale, asymmetry=asymmetry, validate_args=validate_args, allow_nan_stats=allow_nan_stats, name=name, shape=shape, sample=sample, seed=seed, obs=obs, wrap=wrap)

    @staticmethod
    def wishart(concentration=None, scale_matrix=None, rate_matrix=None, scale_tril=None, df=None, validate_args=False, allow_nan_stats=True, name='Wishart', mask=None, shape=(), sample=False, seed=None, obs=None, wrap=True, create_obj=False):
        """
        Wrapper for tfd.WishartTriL.
        concentration is the degrees of freedom (numpyro name); df is kept as an alias of concentration.
        """
        if concentration is None:
            concentration = df
        elif df is not None:
            raise ValueError("wishart: pass concentration (numpyro name) or df, not both.")
        if concentration is None:
            raise ValueError("wishart needs concentration (degrees of freedom).")
        if scale_tril is None:
            if scale_matrix is not None:
                scale_tril = jnp.linalg.cholesky(scale_matrix)
            elif rate_matrix is not None:
                scale_tril = jnp.linalg.cholesky(jnp.linalg.inv(rate_matrix))
            else:
                raise ValueError("wishart needs one of scale_matrix, rate_matrix or scale_tril.")
        dist = tfd.WishartTriL(df=concentration, scale_tril=scale_tril, validate_args=validate_args, allow_nan_stats=allow_nan_stats, name=name)
        return UnifiedDist._finish(dist, shape=shape, sample=sample, seed=seed, obs=obs, wrap=wrap, mask=mask, create_obj=create_obj, name=name)

    @staticmethod
    def truncated_distribution(distribution, low=None, high=None, validate_args=False, allow_nan_stats=True, name='TruncatedDistribution', mask=None, shape=(), sample=False, seed=None, obs=None, wrap=True, create_obj=False):
        """
        Wrapper for tfd.TruncatedDistribution.

        Note: differs from the numpyro backend: the base-distribution keyword
        is base_dist in np_dists.truncated_distribution, not distribution.
        """
        dist = tfd.TruncatedDistribution(distribution=distribution, low=low, high=high, validate_args=validate_args, allow_nan_stats=allow_nan_stats, name=name)
        return UnifiedDist._finish(dist, shape=shape, sample=sample, seed=seed, obs=obs, wrap=wrap, mask=mask, create_obj=create_obj, name=name)


