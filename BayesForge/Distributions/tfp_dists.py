    def discrete_uniform(low, high, validate_args=False, allow_nan_stats=True, name='DiscreteUniform', mask=None, shape=(), sample=False, seed=None, obs=None, wrap=True, create_obj=False):
        """
        Discrete uniform on the integers low..high (pmf 1 / (high - low + 1)),
        as numpyro DiscreteUniform. low and high must be concrete integers.
        """
        # Integer outcomes so sample=True keeps the int32 dtype the old
        # explicit .astype(jnp.int32) produced (tfd.FiniteDiscrete supports
        # integer outcomes and compares them exactly).
        outcomes = jnp.arange(int(low), int(high) + 1, dtype=jnp.int32)
        dist = tfd.FiniteDiscrete(outcomes=outcomes, probs=jnp.full(outcomes.shape, 1.0 / outcomes.shape[0]), validate_args=validate_args, allow_nan_stats=allow_nan_stats, name=name)
        return UnifiedDist._finish(dist, shape=shape, sample=sample, seed=seed, obs=obs, wrap=wrap, mask=mask, create_obj=create_obj, name=name)

