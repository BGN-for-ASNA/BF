    @staticmethod
    def gamma_poisson(concentration, rate=None, scale=None, validate_args=False, allow_nan_stats=True, name='GammaPoisson', shape=(), sample=False, seed=None, obs=None, wrap=True):
        """
        Alias for NegativeBinomial (often used in rethinking).
        """
        if rate is None:
            rate = 1.0 / scale if scale is not None else 1.0
        # numpyro GammaPoisson(concentration, rate) = NegativeBinomial with
        # mean concentration / rate. TFP's NB mean is total_count * p / (1 - p),
        # so p / (1 - p) = 1 / rate, i.e. p = 1 / (1 + rate).
        # (variance check: n p / (1-p)^2 = c (1 + rate) / rate^2 = c/rate + c/rate^2.)
        probs = 1.0 / (1.0 + jnp.asarray(rate))
        return UnifiedDist.negative_binomial(total_count=concentration, probs=probs, validate_args=validate_args, allow_nan_stats=allow_nan_stats, require_integer_total_count=False, name=name, shape=shape, sample=sample, seed=seed, obs=obs, wrap=wrap)

    @staticmethod
    def gaussian_random_walk(scale=1.0, num_steps=1, loc=0., validate_args=False, allow_nan_stats=True, name='GaussianRandomWalk', mask=None, shape=(), sample=False, seed=None, obs=None, wrap=True, create_obj=False):
        """
        Wrapper for a Gaussian Random Walk.
        """
        # TFP implementation using TransformedDistribution and a Chain of Shift + Cumsum
        base_dist = tfd.Sample(tfd.Normal(loc=jnp.zeros_like(jnp.asarray(scale, dtype=float)), scale=scale), sample_shape=(num_steps,))
        dist = tfd.TransformedDistribution(distribution=base_dist, bijector=tfb.Chain([tfb.Shift(jnp.asarray(loc, dtype=float)), tfb.Cumsum()]), name=name)
        return UnifiedDist._finish(dist, shape=shape, sample=sample, seed=seed, obs=obs, wrap=wrap, mask=mask, create_obj=create_obj, name=name)

